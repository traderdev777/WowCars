/**
 * Returns available models for a manufacturer
 */
export function getModelsForMake(make: string): string[] {
  return MANUFACTURER_MODELS[make] || [
    "Standard Model",
    "Other / Custom Model",
  ];
}

/**
 * Returns available variants for a make and model
 */
export function getVariantsForModel(make: string, model: string): string[] {
  const key = `${make}:${model}`;
  if (MODEL_VARIANTS[key]) {
    return MODEL_VARIANTS[key];
  }

  // Common luxury / European fallback
  if (
    make === "BMW" ||
    make === "Mercedes-Benz" ||
    make === "Audi" ||
    make === "Volvo" ||
    make === "Lexus" ||
    make === "Jaguar" ||
    make === "Land Rover" ||
    make === "Porsche"
  ) {
    return [
      "Standard",
      "Base Variant",
      "Mid Variant",
      "Top Variant / Luxury Line",
      "M Sport / AMG Line / S Line",
      "Other / Custom Trim",
    ];
  }

  // General Indian automotive fallback
  return [
    "Base Variant",
    "Mid Variant",
    "Top End Variant",
    "Top End Optional",
    "Other / Custom Trim",
  ];
}

/**
 * Returns model-verified or manufacturer colors alongside comprehensive options
 */
export function getColorsForModel(make: string, _model: string): ColorOption[] {
  if (MANUFACTURER_VERIFIED_COLORS[make]) {
    return MANUFACTURER_VERIFIED_COLORS[make];
  }
  return COMPREHENSIVE_COLORS.slice(0, 10);
}
